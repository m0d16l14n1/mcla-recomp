#!/bin/sh
# Records a drive of yours for route-test.sh: starts the game on Metal with keyboard and trackpad
# (Return = Start, Space = A, Backspace = B, WASD, arrows = camera, W/E/O throttle, S/Q/I brake), logs
# the car's position 4 times a second from free roam on (40 minutes at most), and records the pad.
# Quit the game when done, then make a route from the log:
#   python3 launcher/dev/route.py from-pos out/research/drives/<name>.log launcher/dev/drive-test/<name>.route
# usage: record-drive.sh <name> [game options...]
here=$(cd "$(dirname "$0")" && pwd)
cd "$here/../../.." || exit 1
D=$PWD/out/research/drives; mkdir -p "$D"
name=$1; shift
pad=$D/record-$name.pad
{
  echo "# Generated by record-drive.sh: marks free roam, then logs the position 4 times a second (40 min)."
  echo "wait_until roam 1800s"
  echo "mark free_roam"
  i=0; while [ $i -lt 9600 ]; do echo "pos"; echo "wait 250ms"; i=$((i + 1)); done
} > "$pad"
sh scripts/play_mac.sh --fullscreen=false --mcla_gpu_backend=metal --mnk_mode=true --mnk_mouse=true \
  --keybind_right_trigger=W,E,O --keybind_left_trigger=S,Q,I \
  --mcla_pad_script="$pad" --mcla_pad_record="$D/$name.csv" --log_file="$D/$name.log" "$@"
