#!/bin/sh
# Drives a recorded route N times and prints one line per run: how many of the 240 position samples
# (4 a second for 60 s) were under the road (Y < 10; the road is at 14.5 to 18 on drive-short.route),
# the lowest Y, the backend's last frame time, and whether the route was finished.
#
# usage: [BACKEND=metal|vulkan] [ROUTE=file.route] route-test.sh <label> <runs> [game options...]
#   e.g. route-test.sh uncapped 3 --mcla_fps=0
# Logs: out/research/drives/t-<label>-<run>.log. Needs the game data where scripts/play_mac.sh finds it.
# See launcher/dev/metal-car-falls-2026-11-01.md.
here=$(cd "$(dirname "$0")" && pwd)
cd "$here/../../.." || exit 1
D=$PWD/out/research/drives; mkdir -p "$D"
label=$1; runs=$2; shift 2
backend=${BACKEND:-metal}; route=${ROUTE:-$here/drive-short.route}
case $route in /*) ;; *) route=$PWD/$route ;; esac
pad=$D/follow-$label.pad
{
  echo "# Generated by route-test.sh: boot to free roam, drive $route, log the position 4 times a second."
  echo "wait 35s"
  echo "press_until start left_title every=2s timeout=120s"
  echo "press_until a roam every=3s timeout=240s"
  echo "wait 3s"
  echo "mark drive"
  echo "follow $route"
  i=0; while [ $i -lt 240 ]; do echo "pos"; echo "wait 250ms"; i=$((i + 1)); done
  echo "wait_until follow_done 60s"
  echo "mark drive_end"
  echo "quit"
} > "$pad"
for run in $(seq 1 "$runs"); do
  log=$D/t-$label-$run.log; rm -f "$log" "$D"/t-$label-$run.*.log
  timeout 200 sh scripts/play_mac.sh --fullscreen=false --mcla_gpu_backend=$backend --mcla_pad_script="$pad" --log_file="$log" "$@" > /dev/null 2>&1
  pkill -9 mcla 2> /dev/null
  falls=$(grep "pos -> ok" "$log" | awk '{y=$(NF-1); if (y<10) bad++; if (y<min||NR==1) min=y} END {printf "%d/%d below Y 10, min Y %s", bad, NR, min}')
  ms=$(grep -o "frame time: [0-9.]* ms" "$log" | tail -1)
  end=$(grep -c "follow reached" "$log")
  crash=$(grep -c "Unhandled guest access" "$log")
  echo "$label run $run: $falls; $ms; route finished: $end; guest access violations: $crash"
done
